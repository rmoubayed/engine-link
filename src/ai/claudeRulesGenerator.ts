/**
 * Generate a CLAUDE.md file at the project root for Claude Code.
 *
 * Claude Code reads CLAUDE.md (or .claude/CLAUDE.md) for project-specific
 * instructions. This mirrors the Cursor rules but in a single combined file.
 */

import * as fs from 'fs';
import * as path from 'path';
import type { UEProject } from '../types';

/**
 * Generate CLAUDE.md at the project root if it doesn't already exist.
 */
export async function generateClaudeRules(project: UEProject): Promise<void> {
  const filePath = path.join(project.projectRoot, 'CLAUDE.md');

  // Non-destructive: only write if file doesn't exist
  try {
    await fs.promises.access(filePath);
    return;
  } catch {
    // File doesn't exist — proceed
  }

  const content = buildClaudeMdContent(project.name);
  await fs.promises.writeFile(filePath, content, 'utf-8');
}

function buildClaudeMdContent(projectName: string): string {
  return `# ${projectName} — Unreal Engine Project

> This file provides Unreal Engine guidance to Claude Code.
> It was auto-generated by EngineLink and won't overwrite manual changes.

---

## Unreal Engine C++ Naming Conventions

### Class Prefixes
- **U** prefix: Classes deriving from UObject (e.g., \`UActorComponent\`, \`UUserWidget\`)
- **A** prefix: Classes deriving from AActor (e.g., \`ACharacter\`, \`APlayerController\`)
- **F** prefix: Structs and non-UObject classes (e.g., \`FVector\`, \`FString\`)
- **E** prefix: Enums (e.g., \`ECollisionChannel\`, \`EMovementMode\`)
- **I** prefix: Interfaces (e.g., \`IInteractable\`)
- **T** prefix: Templates (e.g., \`TArray\`, \`TMap\`, \`TSubclassOf\`)

### Coding Style
- PascalCase for all function names, variables, and types
- Boolean variables start with \`b\` (e.g., \`bIsActive\`, \`bCanJump\`)
- Use \`int32\`, \`uint8\`, \`float\` instead of \`int\`, \`unsigned char\`, etc.
- Use \`FString\` instead of \`std::string\`
- Use \`TArray\` instead of \`std::vector\`
- Use \`TMap\` instead of \`std::unordered_map\`
- Use \`MakeShared\`/\`TSharedPtr\` instead of \`std::shared_ptr\`
- Include the matching header first, then Engine headers, then project headers
- Use \`#pragma once\` instead of include guards
- Always use \`TEXT()\` macro for string literals passed to UE APIs

---

## UE Reflection Macros

### UCLASS()
\`\`\`cpp
UCLASS(BlueprintType, Blueprintable)
class MYPROJECT_API AMyActor : public AActor
{
    GENERATED_BODY()
public:
    AMyActor();
};
\`\`\`
Common specifiers: \`BlueprintType\`, \`Blueprintable\`, \`Abstract\`, \`NotBlueprintable\`, \`ClassGroup\`

### UPROPERTY()
\`\`\`cpp
UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "Combat")
float Health = 100.0f;
\`\`\`
Common specifiers: \`EditAnywhere\`, \`VisibleAnywhere\`, \`BlueprintReadOnly\`, \`BlueprintReadWrite\`, \`Category\`, \`Replicated\`, \`ReplicatedUsing\`

### UFUNCTION()
\`\`\`cpp
UFUNCTION(BlueprintCallable, Category = "Combat")
void TakeDamage(float DamageAmount);
\`\`\`
Common specifiers: \`BlueprintCallable\`, \`BlueprintPure\`, \`BlueprintImplementableEvent\`, \`BlueprintNativeEvent\`, \`Server\`, \`Client\`, \`NetMulticast\`

### USTRUCT() / UENUM()
\`\`\`cpp
USTRUCT(BlueprintType)
struct FMyStruct { GENERATED_BODY() UPROPERTY(EditAnywhere) float Value; };

UENUM(BlueprintType)
enum class EMyEnum : uint8 { None, Option1, Option2 };
\`\`\`

### GENERATED_BODY()
Must be the first line inside every UCLASS/USTRUCT. Do not add anything before it.

---

## UE Build System

### Module Structure
Each module has: \`ModuleName.Build.cs\`, \`Public/\`, \`Private/\`, and optionally \`Classes/\`.

### .Build.cs
\`\`\`csharp
public class MyModule : ModuleRules
{
    public MyModule(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;
        PublicDependencyModuleNames.AddRange(new string[] { "Core", "CoreUObject", "Engine" });
        PrivateDependencyModuleNames.AddRange(new string[] { "Slate", "SlateCore" });
    }
}
\`\`\`

### Dependency Rules
- **PublicDependencyModuleNames**: Other modules that depend on yours also get these
- **PrivateDependencyModuleNames**: Only your module gets these
- Prefer Private when possible to reduce compile times

---

## Live Coding Limitations

Live Coding (Ctrl+Alt+F11) hot-patches binaries at runtime.

### Cannot Do
- Add or remove UPROPERTY members
- Add or remove UFUNCTION methods
- Change UFUNCTION signatures (return type, name, parameters)
- Add or remove UCLASS/USTRUCT/UENUM declarations
- Change class inheritance hierarchy
- Modify constructors of UObject-derived classes

### Can Do
- Modify function body logic
- Change local variables
- Modify non-reflected member variables
- Add/modify non-reflected helper functions

**Best Practice**: If you need to add/remove reflected members, do a full Build instead of Live Coding.

---

## Common UE Patterns

### Delegates
\`\`\`cpp
DECLARE_DYNAMIC_MULTICAST_DELEGATE_OneParam(FOnHealthChanged, float, NewHealth);
UPROPERTY(BlueprintAssignable)
FOnHealthChanged OnHealthChanged;
OnHealthChanged.Broadcast(CurrentHealth);
\`\`\`

### Timers
\`\`\`cpp
GetWorldTimerManager().SetTimer(TimerHandle, this, &AMyActor::DoSomething, 2.0f, false);
GetWorldTimerManager().ClearTimer(TimerHandle);
\`\`\`

### Subsystems
\`\`\`cpp
UMySubsystem* Sub = GetGameInstance()->GetSubsystem<UMySubsystem>();
\`\`\`

### Logging
\`\`\`cpp
DECLARE_LOG_CATEGORY_EXTERN(LogMyGame, Log, All);  // header
DEFINE_LOG_CATEGORY(LogMyGame);                     // cpp
UE_LOG(LogMyGame, Warning, TEXT("Health: %f"), Health);
\`\`\`

### Spawning Actors
\`\`\`cpp
FActorSpawnParameters SpawnParams;
SpawnParams.Owner = this;
AMyActor* Actor = GetWorld()->SpawnActor<AMyActor>(ActorClass, Location, Rotation, SpawnParams);
\`\`\`
`;
}
